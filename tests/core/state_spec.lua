local store = require("review.core.store")
local events = require("review.core.events")
local state = require("review.core.state")

describe("core.state", function()
  before_each(function()
    local tmp = vim.fn.tempname(); vim.fn.mkdir(tmp, "p")
    store.root_fn = function() return tmp end
    state._reset()
  end)

  it("add assigns defaults and emits comments:changed", function()
    local fired = false
    events.on("comments:changed", function() fired = true end)
    local c = state.add({ path = "a.ts", lnum = 5, text = "x" })
    assert.is_truthy(c.id); assert.is_false(c.resolved); assert.are.equal("user", c.author)
    assert.are.equal(5, c.end_lnum)
    vim.wait(50, function() return fired end)
    assert.is_true(fired)
  end)

  it("persist + load round-trip", function()
    state.add({ path = "a.ts", lnum = 1, text = "x" })
    state.persist(); state._reset(); state.load()
    assert.are.equal(1, #state.all())
  end)

  it("remove and update by id", function()
    local c = state.add({ path = "a.ts", lnum = 1, text = "x" })
    assert.is_true(state.update(c.id, { resolved = true }))
    assert.is_true(state.by_id(c.id).resolved)
    assert.is_true(state.remove(c.id))
    assert.are.equal(0, #state.all())
  end)

  it("for_path filters", function()
    state.add({ path = "a.ts", lnum = 1, text = "x" })
    state.add({ path = "b.ts", lnum = 1, text = "y" })
    assert.are.equal(1, #state.for_path("a.ts"))
  end)

  it("persist saves to the repo it was loaded from even if the cwd moves to another repo", function()
    local repo_a = store.root_fn()
    state.load()
    state.add({ path = "a.ts", lnum = 1, text = "from A" })
    local repo_b = vim.fn.tempname(); vim.fn.mkdir(repo_b, "p")
    store.root_fn = function() return repo_b end
    assert.is_true(state.persist())
    assert.are.equal(1, #store.load(repo_a).comments)
    assert.are.equal(0, vim.fn.filereadable(store.path(repo_b)))
  end)

  it("switch_root saves the previous repo and loads the new one", function()
    local repo_a = store.root_fn()
    state.load()
    state.add({ path = "a.ts", lnum = 1, text = "from A" })
    local repo_b = vim.fn.tempname(); vim.fn.mkdir(repo_b, "p")
    store.save({ version = 1, comments = { { id = "b1", path = "b.ts", lnum = 1, text = "from B" } } }, repo_b)
    store.root_fn = function() return repo_b end
    assert.is_true(state.switch_root())
    assert.are.equal("from B", state.all()[1].text)
    assert.are.equal("from A", store.load(repo_a).comments[1].text)
    assert.is_false(state.switch_root()) -- same repo: no-op
  end)
end)

describe("core.state threading + new fields", function()
  before_each(function()
    local tmp = vim.fn.tempname(); vim.fn.mkdir(tmp, "p")
    store.root_fn = function() return tmp end
    state._reset()
  end)

  it("replies(id) returns only the children of that comment", function()
    local parent = state.add({ path = "a.ts", lnum = 1, text = "question" })
    state.add({ path = "a.ts", lnum = 1, text = "reply 1", reply_to = parent.id, author = "agent" })
    state.add({ path = "a.ts", lnum = 1, text = "reply 2", reply_to = parent.id, author = "agent" })
    state.add({ path = "a.ts", lnum = 2, text = "another top-level" })
    local r = state.replies(parent.id)
    assert.are.equal(2, #r)
    assert.are.equal("reply 1", r[1].text)
  end)

  it("thread(id) returns the parent followed by its replies", function()
    local parent = state.add({ path = "a.ts", lnum = 1, text = "question" })
    state.add({ path = "a.ts", lnum = 1, text = "reply", reply_to = parent.id })
    local t = state.thread(parent.id)
    assert.are.equal(2, #t)
    assert.are.equal(parent.id, t[1].id)
  end)

  it("thread(id) for a nonexistent id returns an empty list", function()
    assert.are.same({}, state.thread("does-not-exist"))
  end)

  it("remove cascades to the comment's replies", function()
    local p = state.add({ path = "a.ts", lnum = 1, text = "parent" })
    state.add({ path = "a.ts", lnum = 1, text = "r1", reply_to = p.id })
    state.add({ path = "a.ts", lnum = 1, text = "r2", reply_to = p.id })
    state.add({ path = "a.ts", lnum = 2, text = "other" })
    assert.is_true(state.remove(p.id))
    assert.are.equal(1, #state.all())        -- only "other" remains
    assert.are.equal(0, #state.replies(p.id)) -- replies deleted
  end)

  it("reply_to/anchor_text/stale survive persist + load", function()
    local p = state.add({ path = "a.ts", lnum = 3, text = "x", anchor_text = "const foo = 1" })
    state.add({ path = "a.ts", lnum = 3, text = "y", reply_to = p.id, author = "agent" })
    state.update(p.id, { stale = true })
    state.persist(); state._reset(); state.load()
    local loaded = state.by_id(p.id)
    assert.are.equal("const foo = 1", loaded.anchor_text)
    assert.is_true(loaded.stale)
    assert.are.equal(1, #state.replies(p.id))
  end)
end)
